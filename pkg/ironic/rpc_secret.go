// rpcCredentialsSecretName returns the name of the RPC bus credentials secret.
func rpcCredentialsSecretName(ironic *metal3api.Ironic) string {
	return ironic.Name + "-rpc-credentials"
}

// RPCSecretRequired returns true when the JSON RPC bus is used and needs its
// own credentials: inter-conductor communication in the highly available
// architecture or communication with the networking service.
func RPCSecretRequired(ironic *metal3api.Ironic) bool {
	return ironic.Spec.HighAvailability || ironic.IsNetworkingServiceEnabled()
}

// EnsureRPCSecret ensures that the RPC bus credentials secret exists while the
// RPC bus is in use, and returns it. The secret is automatically generated by
// the operator and is not shared with the API credentials. When the RPC bus is
// not in use any more, an operator-managed secret is deleted and nil is
// returned. The apiReader is used as a fallback for secrets not yet synced to
// the cache.
func EnsureRPCSecret(cctx ControllerContext, ironic *metal3api.Ironic, apiReader client.Reader) (*corev1.Secret, error) {
	secretName := rpcCredentialsSecretName(ironic)

	if !RPCSecretRequired(ironic) {
		if err := EnsureRPCSecretDeleted(cctx, ironic); err != nil {
			return nil, err
		}
		return nil, nil //nolint:nilnil // no secret is not an error in this context
	}

	existing := &corev1.Secret{}
	err := cctx.Client.Get(cctx.Context, types.NamespacedName{
		Name:      secretName,
		Namespace: ironic.Namespace,
	}, existing)
	if err != nil {
		if !k8serrors.IsNotFound(err) {
			return nil, fmt.Errorf("failed to get RPC credentials secret: %w", err)
		}

		secret, genErr := GenerateSecret(&ironic.ObjectMeta, "rpc", true)
		if genErr != nil {
			return nil, fmt.Errorf("failed to generate RPC credentials: %w", genErr)
		}

		// The name is deterministic so that the secret is re-used on the next reconcile.
		secret.GenerateName = ""
		secret.Name = secretName
		secret.Labels[managedSecretLabel] = managedSecretLabelValue

		if refErr := controllerutil.SetControllerReference(ironic, secret, cctx.Scheme); refErr != nil {
			return nil, fmt.Errorf("failed to set owner reference on RPC credentials secret: %w", refErr)
		}

		cctx.Logger.Info("creating RPC credentials secret", "secret", secretName)
		err = cctx.Client.Create(cctx.Context, secret)
		if err != nil && !k8serrors.IsAlreadyExists(err) {
			// IsAlreadyExists means a race with another reconcile, fall through to fetching
			return nil, fmt.Errorf("failed to create RPC credentials secret: %w", err)
		}
	}

	secret, err := getExternalSecret(cctx, apiReader, ironic.Namespace, secretName)
	if err != nil {
		return nil, err
	}

	// Keep the htpasswd field in sync with the username and password, like
	// it is done for the API credentials secret.
	changed, err := UpdateSecret(secret, logr.Discard())
	if err != nil {
		return nil, fmt.Errorf("cannot update the RPC credentials secret: %w", err)
	}
	if changed {
		cctx.Logger.Info("updating htpasswd", "Secret", secret.Name)
		err = cctx.Client.Update(cctx.Context, secret)
	}

	return secret, err
}

// EnsureRPCSecretDeleted deletes the RPC credentials secret only if it was
// created by the operator (identified by the managedSecretLabel). Externally-
// provided secrets are left untouched.
func EnsureRPCSecretDeleted(cctx ControllerContext, ironic *metal3api.Ironic) error {
	secretName := rpcCredentialsSecretName(ironic)
	secret := &corev1.Secret{}
	if err := cctx.Client.Get(cctx.Context, types.NamespacedName{
		Name:      secretName,
		Namespace: ironic.Namespace,
	}, secret); err != nil {
		if k8serrors.IsNotFound(err) {
			return nil
		}
		return fmt.Errorf("failed to get RPC credentials secret: %w", err)
	}

	// Only delete secrets that the operator created
	if secret.Labels[managedSecretLabel] != managedSecretLabelValue {
		cctx.Logger.Info("skipping deletion of externally-managed RPC credentials secret", "secret", secretName)
		return nil
	}

	if err := cctx.Client.Delete(cctx.Context, secret); err != nil {
		if k8serrors.IsNotFound(err) {
			return nil
		}
		return fmt.Errorf("failed to delete RPC credentials secret: %w", err)
	}

	cctx.Logger.Info("deleted RPC credentials secret", "secret", secretName)
	return nil
}

// GenerateRPCSecret generates a new RPC credentials secret with a fixed name,
// for local (podman) installations.
func GenerateRPCSecret(owner *metav1.ObjectMeta) (*corev1.Secret, error) {
	secret, err := GenerateSecret(owner, "rpc", true)
	if err != nil {
		return nil, err
	}

	// Podman does not support generateName, nor do we need it
	secret.GenerateName = ""
	secret.Name = owner.Name + "-rpc-credentials"

	return secret, nil
}
